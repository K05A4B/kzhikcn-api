func TestUpdate_PublishedAtOnlyOnce(t *testing.T) {
	cleanDB(t)
	svc := newTestService()
	ctx := context.Background()

	article, _ := svc.Create(ctx, &ArticleUpdateFields{
		Title:  ptr("Publish Once"),
		Status: ptr(data.ARTICLE_STATUS_DRAFT),
	})

	updated, _ := svc.Update(ctx, article.ID.String(), ArticleUpdateFields{
		Status: ptr(data.ARTICLE_STATUS_PUBLISHED),
	})
	firstPublished := updated.PublishedAt

	svc.Update(ctx, article.ID.String(), ArticleUpdateFields{
		Status: ptr(data.ARTICLE_STATUS_DRAFT),
	})
	updated, _ = svc.Update(ctx, article.ID.String(), ArticleUpdateFields{
		Status: ptr(data.ARTICLE_STATUS_PUBLISHED),
	})

	assert.True(t, firstPublished.Equal(*updated.PublishedAt))
}

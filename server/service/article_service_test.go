var testDB *gorm.DB

func TestMain(m *testing.M) {
	config.LoadConfig(strings.NewReader(""))

	err := data.ConnectDatabase("sqlite", ":memory:")
	if err != nil {
		panic(err)
	}

	testDB = data.DB()
	testDB.AutoMigrate(&data.Article{}, &data.Category{}, &data.Tag{}, &data.ArticleTag{})

	code := m.Run()

	sqlDB, _ := testDB.DB()
	sqlDB.Close()
	os.Exit(code)
}

func cleanDB(t *testing.T) {
	t.Helper()
	testDB.Exec("DELETE FROM article_tags")
	testDB.Exec("DELETE FROM articles")
	testDB.Exec("DELETE FROM tags")
	testDB.Exec("DELETE FROM categories")
}

func newTestService() *ArticleService {
	ctx := &ServiceContext{
		Conf: &config.Config{},
		Repo: &mockRepo{},
		DB:   testDB,
	}
	return NewArticleService(ctx, nil)
}

func newTestCategory(t *testing.T, name string) *data.Category {
	t.Helper()
	c := &data.Category{CategoryName: name}
	data.DB().Create(c)
	return c
}

func ptr[T any](v T) *T { return &v }

func TestCreate_ValidArticle(t *testing.T) {
	cleanDB(t)
	svc := newTestService()
	ctx := context.Background()

	cat := newTestCategory(t, "go")

	input := &ArticleUpdateFields{
		Title:         ptr("Hello World"),
		Category:      ptr(cat.CategoryName),
		Tags:          []string{"go", "tutorial"},
		Description:   ptr("a test article"),
		EnableComment: ptr(true),
	}

	article, err := svc.Create(ctx, input)
	require.NoError(t, err)
	assert.NotNil(t, article)
	assert.Equal(t, "Hello World", article.Title)
	assert.Equal(t, "go", article.Category.CategoryName)
	assert.Len(t, article.Tags, 2)
	assert.Equal(t, "a test article", article.Description)
	assert.True(t, article.EnableComment)
}

